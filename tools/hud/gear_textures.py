"""Embeds the gear display textures in the .asi.

Usage: python gear_textures.py <dir with drive.png and reverse.png> <output .h>

Writes each texture as D3DFMT_A8R8G8B8 pixels (0xAARRGGBB words, rows top to bottom) for src/gear_hud.cpp.
"""
import sys
from pathlib import Path

from PIL import Image


def array(name, path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    words = [f"0x{a:02X}{r:02X}{g:02X}{b:02X}u" for r, g, b, a in im.get_flattened_data()]
    rows = [", ".join(words[i:i + 8]) for i in range(0, len(words), 8)]
    body = ",\n    ".join(rows)
    return (f"constexpr int k{name}Width = {w}, k{name}Height = {h};\n"
            f"constexpr std::uint32_t k{name}[] = {{\n    {body},\n}};\n")


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    text = ("// Generated by tools/hud/gear_textures.py from " + src.as_posix() + ". Do not edit.\n"
            "#pragma once\n#include <cstdint>\n\n"
            + array("GearDrive", src / "drive.png") + "\n"
            + array("GearReverse", src / "reverse.png"))
    out.write_text(text, newline="\n")


if __name__ == "__main__":
    main()
